def read_input(path):
    """Read a complete native payload while retaining any original I/O failure."""
    try:
        return path.read_bytes()
    except OSError as failure:
        raise GenerationError("input-read", path, "a readable retained input file", failure) from failure


def decode_input(data, path):
    """Decode UTF-8 while retaining a native decoder failure and its original bytes."""
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError as failure:
        raise GenerationError("input-encoding", path, "UTF-8 input", failure) from failure


def load_inputs(directory):
    """Verify every retained input's release, official URL, digest, and encoding."""
    manifest_path = directory / "sources.json"
    try:
        manifest = json.loads(decode_input(read_input(manifest_path), manifest_path))
    except json.JSONDecodeError as failure:
        raise GenerationError("input-manifest-json", manifest_path, "valid source-manifest JSON", failure) from failure
    if not isinstance(manifest, dict):
        raise GenerationError("input-manifest", manifest_path, "a source manifest object", manifest)
    if manifest.get("unicode_version") != UNICODE_VERSION_NUMBER:
        raise GenerationError("input-version", manifest_path, UNICODE_VERSION_NUMBER,
                              manifest.get("unicode_version"))
    files = manifest.get("files")
    if not isinstance(files, dict) or set(files) != set(INPUT_FILES):
        raise GenerationError("input-files", manifest_path, INPUT_FILES, files)
    inputs = {}
    for name in INPUT_FILES:
        path = directory / name
        entry = files[name]
        expected_url = f"https://www.unicode.org/Public/{UNICODE_VERSION_NUMBER}/ucd/{name}"
        if not isinstance(entry, dict) or entry.get("url") != expected_url:
            raise GenerationError("input-source", manifest_path, expected_url, entry)
        data = read_input(path)
        digest = hashlib.sha256(data).hexdigest()
        if digest != entry.get("sha256"):
            raise GenerationError("input-digest", path, entry.get("sha256"), digest)
        inputs[name] = decode_input(data, path)
    release = f"final data files for version {UNICODE_VERSION_NUMBER}"
    if release not in inputs["ReadMe.txt"]:
        raise GenerationError("release-metadata", directory / "ReadMe.txt", release,
                              inputs["ReadMe.txt"])
    for name, header in (
        ("emoji/emoji-data.txt", f"# Version: {UNICODE_VERSION_NUMBER}"),
        ("extracted/DerivedGeneralCategory.txt", f"# DerivedGeneralCategory-{UNICODE_VERSION_NUMBER}.txt"),
    ):
        if header not in inputs[name].splitlines():
            raise GenerationError("property-version", directory / name, header, inputs[name].splitlines()[:10])
    return inputs


def code_point(text, source, line):
    """Parse one UCD hexadecimal code point within the Unicode codespace."""
    if not re.fullmatch(r"[0-9A-Fa-f]{4,6}", text):
        raise GenerationError("code-point", source, "four to six hexadecimal digits", text, line)
    value = int(text, 16)
    if value > 0x10FFFF:
        raise GenerationError("code-point", source, "at most U+10FFFF", value, line)
    return value


def append_range(ranges, start, end, source, line, value=None):
    """Keep ranges ordered, disjoint, and nonempty while retaining their values."""
    if start > end or (ranges and start <= ranges[-1][1]):
        raise GenerationError("range-order", source, "ordered disjoint nonempty ranges",
                              (ranges[-1:] or None, start, end, value), line)
    ranges.append((start, end) if value is None else (start, end, value))


def load_emoji_properties(text, source):
    """Parse the official binary-property records and validate each property."""
    kinds = {name: [] for name in (*EMOJI_PROPERTIES, "Extended_Pictographic")}
    for number, raw in enumerate(text.splitlines(), 1):
        record = raw.partition("#")[0].strip()
        if not record:
            continue
        fields = record.split(";")
        if len(fields) != 2 or fields[1].strip() not in kinds:
            raise GenerationError("emoji-record", source, "code-point range and supported property", raw, number)
        bounds = fields[0].strip().split("..")
        if len(bounds) not in (1, 2):
            raise GenerationError("emoji-range", source, "one code point or one inclusive range", raw, number)
        start = code_point(bounds[0], source, number)
        end = code_point(bounds[-1], source, number)
        if start <= 0xDFFF and end >= 0xD800:
            raise GenerationError("emoji-surrogate", source, "only Unicode scalar ranges",
                                  (fields[1].strip(), start, end), number)
        append_range(kinds[fields[1].strip()], start, end, source, number)
    for name in EMOJI_PROPERTIES:
        if not kinds[name]:
            raise GenerationError("emoji-property", source, "nonempty required property", name)
    return kinds


def load_general_category_properties(text, source):
    """Parse categories, including validated paired First/Last range records."""
    ranges = []
    pending = None
    for number, raw in enumerate(text.splitlines(), 1):
        if not raw.strip() or raw.startswith("#"):
            continue
        fields = raw.split(";")
        if len(fields) != 15 or fields[2] not in GENERAL_CATEGORY_VARIANTS:
            raise GenerationError("category-record", source, "15 fields and a known category", raw, number)
        point = code_point(fields[0], source, number)
        name, category = fields[1:3]
        first = re.fullmatch(r"<(.*), First>", name)
        last = re.fullmatch(r"<(.*), Last>", name)
        if first and pending is None:
            pending = (point, first.group(1), category, number)
            continue
        if last and pending is not None and (last.group(1), category) == pending[1:3]:
            append_range(ranges, pending[0], point, source, number, category)
            pending = None
        elif pending is not None or last is not None:
            raise GenerationError("category-pair", source, "matching adjacent First/Last records",
                                  (pending, raw), number)
        else:
            append_range(ranges, point, point, source, number, category)
    if pending is not None or not ranges:
        raise GenerationError("category-completeness", source, "nonempty data and complete range pairs", pending)
    for start, end, category in ranges:
        if ((category == "Cs" and not 0xD800 <= start <= end <= 0xDFFF)
                or (category != "Cs" and start <= 0xDFFF and end >= 0xD800)):
            raise GenerationError("category-surrogate", source,
                                  "surrogates confined to category Cs and U+D800..U+DFFF", (start, end, category))
    return ranges

def format_table_content(f, content, indent):
    line = " "*indent
    first = True
    for chunk in content.split(","):
        if len(line) + len(chunk) < 98:
            if first:
                line += chunk
            else:
                line += ", " + chunk
            first = False
        else:
            f.write(line + ",\n")
            line = " "*indent + chunk
    f.write(line)

def escape_char(c):
    if c == 'multi':
        return "\"<multiple code points>\""
    return "'\\u{%x}'" % c

def escape_char_list(l):
    line = "["
    first = True
    for c in l:
        if first:
            line += escape_char(c)
        else:
            line += ", " + escape_char(c)
        first = False
    line += "]"
    return line

def emit_table(f, name, t_data, t_type = "&'static [(char, char)]", is_pub=True,
        pfun=lambda x: "(%s,%s)" % (escape_char(x[0]), escape_char(x[1])), is_const=True):
    pub_string = "const"
    if not is_const:
        pub_string = "let"
    if is_pub:
        pub_string = "pub " + pub_string
    f.write("    %s %s: %s = &[\n" % (pub_string, name, t_type))
    data = ""
    first = True
    for dat in t_data:
        if not first:
            data += ","
        first = False
        data += pfun(dat)
    format_table_content(f, data, 8)
    f.write("\n    ];\n\n")

