def emit_util_mod(f):
    """Emit a shared lookup only when a property feature needs it."""
    f.write("""
#[cfg(any(feature = "general-category", feature = "emoji"))]
/// Shared lookup over sorted, disjoint scalar ranges.
mod util {
    use core::result::Result::{Ok, Err};

    /// Return the value belonging to the containing range, or the native absence.
    pub(super) fn bsearch_range_value_table<T: Copy>(c: char, r: &'static [(char, char, T)]) -> Option<T> {
        use core::cmp::Ordering::{Equal, Less, Greater};
        match r.binary_search_by(|&(lo, hi, _)| {
            if lo <= c && c <= hi { Equal }
            else if hi < c { Less }
            else { Greater }
        }) {
            Ok(idx) => r.get(idx).map(|&(_, _, cat)| cat),
            Err(_) => None
        }
    }

}

""")

def build_emoji_table(properties, source):
    """Partition the scalar domain by the five supported binary properties."""
    combinations = {
        frozenset(): "NonEmoji",
        frozenset(("Emoji_Component",)): "NonEmojiButEmojiComponent",
        frozenset(("Emoji",)): "EmojiOther",
        frozenset(("Emoji", "Emoji_Presentation")): "EmojiPresentation",
        frozenset(("Emoji", "Emoji_Modifier_Base")): "EmojiModifierBase",
        frozenset(("Emoji", "Emoji_Presentation", "Emoji_Modifier_Base")): "EmojiPresentationAndModifierBase",
        frozenset(("Emoji", "Emoji_Component")): "EmojiOtherAndEmojiComponent",
        frozenset(("Emoji", "Emoji_Presentation", "Emoji_Component")): "EmojiPresentationAndEmojiComponent",
        frozenset(("Emoji", "Emoji_Presentation", "Emoji_Modifier", "Emoji_Component")):
            "EmojiPresentationAndModifierAndEmojiComponent",
    }
    boundaries = {0, 0xD800, 0xE000, 0x110000}
    for name in EMOJI_PROPERTIES:
        for start, end in properties[name]:
            if start <= 0xDFFF and end >= 0xD800:
                raise GenerationError("emoji-surrogate", source, "only Unicode scalar ranges", (name, start, end))
            boundaries.update((start, end + 1))
    boundaries = sorted(boundaries)
    positions = dict.fromkeys(EMOJI_PROPERTIES, 0)
    table = []
    for start, stop in zip(boundaries, boundaries[1:]):
        if 0xD800 <= start <= 0xDFFF:
            continue
        active = set()
        for name in EMOJI_PROPERTIES:
            ranges = properties[name]
            while positions[name] < len(ranges) and ranges[positions[name]][1] < start:
                positions[name] += 1
            if positions[name] < len(ranges) and ranges[positions[name]][0] <= start:
                active.add(name)
        active = frozenset(active)
        if active not in combinations:
            raise GenerationError("emoji-combination", source, "a supported EmojiStatus combination",
                                  (start, stop - 1, active))
        status = combinations[active]
        if table and table[-1][1] + 1 == start and table[-1][2] == status:
            table[-1] = (table[-1][0], stop - 1, status)
        else:
            table.append((start, stop - 1, status))
    return table


@dataclass
class PreparedTables:
    """Retain the complete validated inputs and both prepared property tables."""

    inputs: dict
    categories: list
    emoji: list


@dataclass
class GeneratedTables:
    """Retain the prepared subject, rendered output, and committed destination."""

    prepared: PreparedTables
    rendered: str
    output: Path


def prepare_tables(directory):
    """Load and validate both property families before rendering any output."""
    inputs = load_inputs(directory)
    categories = load_general_category_properties(inputs["UnicodeData.txt"], directory / "UnicodeData.txt")
    properties = load_emoji_properties(inputs["emoji/emoji-data.txt"], directory / "emoji/emoji-data.txt")
    emoji = build_emoji_table(properties, directory / "emoji/emoji-data.txt")
    return PreparedTables(inputs, categories, emoji)


def render_tables(prepared):
    """Render the complete prepared release without filesystem effects."""
    output = io.StringIO()
    output.write(preamble)
    output.write(f"// Unicode input provenance: tests/data/unicode/{UNICODE_VERSION_NUMBER}/sources.json\n")
    output.write("""
/// The Unicode release supplying every generated property table in this crate.
pub const UNICODE_VERSION: (u64, u64, u64) = (%s, %s, %s);

""" % UNICODE_VERSION)
    emit_util_mod(output)
    emit_general_category_module(output, prepared.categories)
    emit_emoji_module(output, prepared.emoji)
    return output.getvalue()


def write_atomic(output, rendered):
    """Commit one complete file while preserving the prior file on failure."""
    mode = stat.S_IMODE(output.stat().st_mode) if output.exists() else 0o644
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n",
                                         dir=output.parent, prefix=f".{output.name}.", delete=False) as handle:
            temporary = Path(handle.name)
            handle.write(rendered)
            handle.flush()
            os.fsync(handle.fileno())
            os.chmod(temporary, mode)
        os.replace(temporary, output)
    except Exception as primary:
        if temporary is not None:
            try:
                temporary.unlink(missing_ok=True)
            except OSError as cleanup:
                raise OutputWriteFailure(output, temporary, primary, cleanup) from primary
        raise


def generate(directory, output, progress=lambda phase: None):
    """Validate, render, and atomically commit the complete selected release."""
    progress("validate official input bundle")
    prepared = prepare_tables(directory)
    progress("render complete property tables")
    rendered = render_tables(prepared)
    progress(f"replace {display_path(output)}")
    write_atomic(output, rendered)
    return GeneratedTables(prepared, rendered, output)


def main():
    """Keep the legacy tables.rs default and expose explicit input/output paths."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-directory", type=Path, default=DEFAULT_DATA_DIRECTORY,
                        help="complete versioned input bundle (default: retained Unicode release)")
    parser.add_argument("--output", type=Path, default=Path("tables.rs"),
                        help="generated Rust file (default: tables.rs in the invocation directory)")
    arguments = parser.parse_args()
    try:
        generated = generate(arguments.data_directory, arguments.output,
                             lambda phase: print(f"Unicode {UNICODE_VERSION_NUMBER}: {phase}", file=sys.stderr))
    except (ValueError, OSError, ExceptionGroup) as failure:
        message = str(failure).replace(str(Path.home()) + "/", "~/")
        print(f"Unicode generation failed: {type(failure).__name__}: {message}", file=sys.stderr)
        if isinstance(failure, OutputWriteFailure):
            print(f"Destination: {display_path(failure.output)}; remaining temporary: "
                  f"{display_path(failure.temporary)}", file=sys.stderr)
            for stage, source in zip(("write", "cleanup"), failure.exceptions):
                detail = str(source).replace(str(Path.home()) + "/", "~/")
                print(f"{stage}: {type(source).__name__}: {detail}", file=sys.stderr)
        return 1
    print(f"Unicode {UNICODE_VERSION_NUMBER}: wrote {display_path(generated.output)} "
          f"({len(generated.prepared.categories)} category input ranges; "
          f"{len(generated.prepared.emoji)} emoji status ranges)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
